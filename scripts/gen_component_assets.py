"""Generate each component's metadata.yaml and README.md, and each category's README.md.

Run it after changing a component; tests/test_assets.py fails if the files are stale.
Layout follows kubeflow/pipelines-components (KEP-913), which asks vendors to keep
the same structure in their own repository.
"""

import inspect
import pathlib
import sys
from importlib import import_module

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1] / "kfp_anakin" / "components"
LAST_VERIFIED = "2026-11-06T00:00:00Z"
CATEGORY_TITLES = {
    "ai_visibility": "AI visibility",
    "browser": "Browser",
    "monitors": "Monitors",
    "web_data": "Web data",
    "wire": "Wire",
}


def component_folders() -> list[pathlib.Path]:
    return sorted(p.parent for p in ROOT.glob("*/*/component.py"))


def load(folder: pathlib.Path):
    module = import_module(f"kfp_anakin.components.{folder.parent.name}.{folder.name}.component")
    return getattr(module, folder.name)


def summary(component) -> str:
    return component.python_func.__doc__.strip().splitlines()[0]


def metadata_text(folder: pathlib.Path) -> str:
    metadata = {
        "name": folder.name,
        "stability": "alpha",
        "dependencies": {
            "kubeflow": [{"name": "Pipelines", "version": ">=2.15.0"}],
            "external_services": [{"name": "Anakin API", "version": "v1"}],
        },
        "tags": ["anakin", "web_data", folder.parent.name],
        "lastVerified": LAST_VERIFIED,
        "links": {
            "documentation": "https://anakin.io/docs/integrations/workflow/kubeflow",
            "issue_tracker": "https://github.com/Anakin-Inc/kfp-anakin/issues",
        },
    }
    return yaml.safe_dump(metadata, sort_keys=False)


def rows(specs: dict) -> list[str]:
    lines = ["| Name | Type | Default |", "|---|---|---|"]
    for name, spec in specs.items():
        kind = getattr(spec, "type", "")
        kind = kind.split("@")[0] if isinstance(kind, str) else str(kind)
        default = "" if not getattr(spec, "optional", False) else repr(spec.default)
        lines.append(f"| `{name}` | {kind} | {f'`{default}`' if default else ''} |")
    return lines


def readme_text(folder: pathlib.Path) -> str:
    component = load(folder)
    spec = component.component_spec
    doc = inspect.cleandoc(component.python_func.__doc__)
    lines = [f"# {folder.name}", "", "```text", doc, "```", "", "## Inputs", ""]
    lines += rows(spec.inputs or {})
    if spec.outputs:
        lines += ["", "## Outputs", "", *rows(spec.outputs)]
    lines += ["", "Generated by `scripts/gen_component_assets.py`.", ""]
    return "\n".join(lines)


def category_readme_text(category: pathlib.Path) -> str:
    lines = [f"# {CATEGORY_TITLES[category.name]}", "", "| Component | What it does |", "|---|---|"]
    for folder in sorted(p.parent for p in category.glob("*/component.py")):
        lines.append(f"| [`{folder.name}`]({folder.name}/README.md) | {summary(load(folder))} |")
    return "\n".join([*lines, ""])


def expected_files() -> dict[pathlib.Path, str]:
    files: dict[pathlib.Path, str] = {}
    for folder in component_folders():
        files[folder / "metadata.yaml"] = metadata_text(folder)
        files[folder / "README.md"] = readme_text(folder)
    for category in sorted(
        p for p in ROOT.iterdir() if (p / "__init__.py").exists() and p.is_dir()
    ):
        files[category / "README.md"] = category_readme_text(category)
    return files


def main() -> int:
    for path, content in expected_files().items():
        path.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
